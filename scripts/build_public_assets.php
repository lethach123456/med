<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require_once dirname(__DIR__) . '/medical_public_assets.php';

// Explicit deploy/build step, never invoked by a public request. Keep CSS cascade byte-for-byte.
try {
    $root = dirname(__DIR__);
    foreach (['shell', 'home'] as $type) {
        $sources = [];
        $css = "/* Generated by scripts/build_public_assets.php; edit the source CSS files. */\n";
        foreach (medical_public_shell_sources($type) as $url) {
            $path = $root . $url;
            if (!is_file($path)) throw new RuntimeException('Missing local source: ' . $url);
            $contents = (string) file_get_contents($path);
            if (preg_match('~@import\s|@charset\s~i', $contents)) {
                throw new RuntimeException('Bundle sources must use absolute asset URLs, no @import/@charset: ' . $url);
            }
            preg_match_all('~url\(\s*([^)]*)\)~i', $contents, $references);
            foreach ($references[1] as $reference) {
                $reference = trim($reference, " \t\n\r\0\x0B'\"");
                if (!str_starts_with($reference, '/') && !preg_match('~^(?:data:|https?://)~i', $reference)) {
                    throw new RuntimeException('Relative asset URL must be made absolute before bundling: ' . $url);
                }
            }
            $sources[$url] = hash('sha256', $contents);
            $css .= "\n/* Source: {$url} */\n" . $contents . "\n";
        }
        $hash = hash('sha256', $css);
        $url = '/assets/css/generated/public-' . $type . '.' . substr($hash, 0, 24) . '.css';
        $directory = $root . '/assets/css/generated';
        if (!is_dir($directory) && !mkdir($directory, 0755, true)) throw new RuntimeException('Cannot create asset output.');
        if (realpath($directory) !== realpath($root) . '/assets/css/generated') throw new RuntimeException('Output cannot be symlinked.');
        $publish = static function (string $path, string $contents) use ($directory): void {
            if (is_link($path)) throw new RuntimeException('Refusing symlinked output.');
            $temporary = tempnam($directory, '.building-');
            if (!is_string($temporary)) throw new RuntimeException('Cannot create temporary asset.');
            try {
                if (file_put_contents($temporary, $contents) !== strlen($contents)
                    || !chmod($temporary, 0644) || !rename($temporary, $path)) throw new RuntimeException('Cannot publish asset.');
            } finally {
                if (is_file($temporary)) unlink($temporary);
            }
        };
        $publish($root . $url, $css);
        $publish($directory . '/public-' . $type . '-manifest.json', json_encode([
            'url' => $url, 'sha256' => $hash, 'sources' => $sources,
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n");
        echo $url . ' ' . strlen($css) . ' B; gzip ' . strlen(gzencode($css, 9)) . " B\n";
    }
} catch (Throwable $error) {
    fwrite(STDERR, $error->getMessage() . "\n");
    exit(1);
}
